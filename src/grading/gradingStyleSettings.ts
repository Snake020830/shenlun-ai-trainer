export const DEFAULT_GRADING_STYLE: GradingStyleProfile = GRADING_STYLE_PRESETS[0];
const PRESET_IDS = new Set<GradingStylePresetId>(["default", "yuan-dong", "bailu", "custom"]);

export function sanitizeGradingStyleProfile(value: unknown): GradingStyleProfile {
  const raw = value && typeof value === "object" && !Array.isArray(value) ? value as Record<string, unknown> : {};
  const presetId = typeof raw.presetId === "string" && PRESET_IDS.has(raw.presetId as GradingStylePresetId)
    ? raw.presetId as GradingStylePresetId
    : "default";
  const name = typeof raw.name === "string" && raw.name.trim()
    ? raw.name.trim().slice(0, 40)
    : presetId === "custom" ? "自定义风格" : (GRADING_STYLE_PRESETS.find(item => item.presetId === presetId)?.name ?? DEFAULT_GRADING_STYLE.name);
  const prompt = typeof raw.prompt === "string" ? raw.prompt.trim().slice(0, GRADING_STYLE_MAX_LENGTH) : "";
  return {
    presetId,
    name,
    prompt,
    ...(typeof raw.updatedAt === "string" ? { updatedAt: raw.updatedAt } : {})
  };
}

export async function loadGradingStyleProfile(): Promise<GradingStyleProfile> {
  const stored = await persistence.getPublicSetting<unknown>(GRADING_STYLE_KEY, DEFAULT_GRADING_STYLE);
  const profile = sanitizeGradingStyleProfile(stored);
  // Upgrade only the exact bundled placeholder. Any user-edited Bailu prompt,
  // even one based on the old preset, remains user-owned and is preserved.
  if (profile.presetId === "bailu" && [LEGACY_BAILU_PLACEHOLDER, LEGACY_BAILU_EVIDENCE_V1].includes(profile.prompt)) {
    return { ...gradingStylePreset("bailu"), ...(profile.updatedAt ? { updatedAt: profile.updatedAt } : {}) };
  }
  return profile;
}

export async function saveGradingStyleProfile(profile: GradingStyleProfile): Promise<GradingStyleProfile> {
  const sanitized = sanitizeGradingStyleProfile({ ...profile, updatedAt: new Date().toISOString() });
  await persistence.setPublicSetting(GRADING_STYLE_KEY, sanitized);
  return sanitized;
}

export function gradingStylePreset(id: Exclude<GradingStylePresetId, "custom">): GradingStyleProfile {
  return { ...(GRADING_STYLE_PRESETS.find(item => item.presetId === id) ?? DEFAULT_GRADING_STYLE) };
}

import type { QuestionType } from "../types";

export const QUESTION_TYPE_SKILL_VERSION = "shenlun-question-type-skill@0.1.0";

const QUESTION_TYPE_GUIDANCE: Record<QuestionType, string> = {
  "概括归纳": [
    "先锁定题干要求概括的对象、范围和问数，再抽取同一对象下的独立信息维度。",
    "概括可以压缩表述，但不得把问题、原因、做法、成效等不同功能的信息混成一个点。",
    "多个主体或多个对象必须先分别归属；只有材料明确支持时才上提共同概念。"
  ].join("\n"),
  "提出对策": [
    "先识别题干要求的是材料既有做法、针对问题提出建议，还是二者兼有。",
    "材料中的既有措施与模型推导出的建议必须区分；不得把建议、设想、规划写成已实施措施。",
    "推导型对策必须能回指材料中的具体问题、原因或约束，并保持主体、对象和动作可执行。"
  ].join("\n"),
  "综合分析": [
    "先明确分析对象以及题干要求解释的含义、关系、原因、影响、观点或评价，再组织材料证据。",
    "不能只做材料摘抄或简单正反罗列；应保留材料支持的逻辑关系、作用机制和必要结论。",
    "材料中的他人观点、事实描述与作答者应形成的综合判断必须区分。"
  ].join("\n"),
  "贯彻执行": [
    "同时识别身份、受众、目的、文种/场景和内容任务；格式要求不能替代实质得分点。",
    "正文内容必须来自题干和材料，按实际沟通目的组织，而不是套固定公文模板。",
    "若题目要求宣传、汇报、发言、建议等不同功能，应据此调整信息选择、语气和结构。"
  ].join("\n"),
  "文章写作": [
    "作文不能按小题关键词清单机械评分。先判断立意是否回应题干核心命题，再看材料运用、论证结构和表达。",
    "材料事实可作为论据或启发，但不得要求考生逐条覆盖所有材料；联系实际也不得被误判为材料外违规补写。",
    "rubric 应优先反映立意契合、论证有效、结构完整、材料转化与表达质量，不以材料点数量直接等价为作文得分。"
  ].join("\n")
};

export function questionTypeSkillInstructions(questionType: QuestionType): string {
  return `题型专用批改约束（${questionType}，${QUESTION_TYPE_SKILL_VERSION}）：\n${QUESTION_TYPE_GUIDANCE[questionType]}`;
}
